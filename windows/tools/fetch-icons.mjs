// Writes renderer/icons.js: the Material Symbols (Rounded, filled, weight 500) PortHop for Windows draws,
// taken from Google's official repository at a fixed commit, plus the icons' licence (Apache 2.0).
// Run: node tools/fetch-icons.mjs
import fs from 'node:fs';

const COMMIT = '10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7';
const RAW = `https://raw.githubusercontent.com/google/material-design-icons/${COMMIT}`;

// PortHop's name for an icon → the Material Symbol drawn for it.
const ICONS = {
  home: 'home', phone: 'smartphone', photo: 'photo_library', eye: 'visibility_off', heart: 'favorite', video: 'videocam',
  live: 'motion_photos_on', shot: 'screenshot_region', selfie: 'account_box', person: 'person', trash: 'delete',
  album: 'photo_album', app: 'apps', info: 'info', clock: 'history', folder: 'folder', file: 'description', msg: 'chat',
  chats: 'forum', note: 'sticky_note_2', music: 'music_note', cal: 'calendar_month', call: 'call', globe: 'language',
  box: 'inventory_2', up: 'upload', down: 'download', arrow: 'arrow_forward', back: 'arrow_back', chev: 'expand_more',
  dots: 'more_horiz', search: 'search', drive: 'hard_drive', cable: 'cable', lock: 'lock', refresh: 'refresh',
  restart: 'restart_alt', moon: 'bedtime', sun: 'light_mode', contrast: 'contrast', plus: 'add', warn: 'warning', check: 'check', camera: 'photo_camera',
  bolt: 'bolt', locoff: 'location_off', report: 'summarize', update: 'system_update_alt', wifi: 'wifi', pdf: 'picture_as_pdf', mic: 'mic',
  contact: 'contacts', event: 'event', terminal: 'terminal', backup: 'backup',
};

async function get(path) {
  const r = await fetch(`${RAW}/${path}`);
  if (!r.ok) throw new Error(`${path}: HTTP ${r.status}`);
  return r.text();
}

const out = {};
for (const [key, name] of Object.entries(ICONS)) {
  const svg = await get(`symbols/web/${name}/materialsymbolsrounded/${name}_wght500fill1_24px.svg`);
  if (!/viewBox="0 -960 960 960"/.test(svg)) throw new Error(`${name}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`${name}: no path`);
  out[key] = paths.join(' ');
}
const body = Object.entries(out).map(([k, d]) => `  ${k}: '${d}',`).join('\n');
fs.writeFileSync(new URL('../renderer/icons.js', import.meta.url),
  `// Generated by tools/fetch-icons.mjs from Material Symbols (Rounded, filled, weight 500), google/material-design-icons@${COMMIT.slice(0, 12)}.\n` +
  `// Licence: Apache 2.0, see icons-LICENSE.txt. Drawn in a 960-unit box: viewBox="0 -960 960 960".\n` +
  `const MATERIAL_ICONS = {\n${body}\n};\n`);
fs.writeFileSync(new URL('../renderer/icons-LICENSE.txt', import.meta.url),
  `Material Symbols, from https://github.com/google/material-design-icons (commit ${COMMIT}).\n\n` + await get('LICENSE'));
console.log('icons.js:', Object.keys(out).length, 'icons');
